"""Puts reviewed AI scenes into the game.

For each name: trims black letterbox bars, crops to 16:9, saves public/scenes/<name>.jpg at
960x540, marks it done in scenes.json and lists it in src/components/art/aiStills.ts (so the
place shows the still instead of the old stock video).
Usage: python3 scripts/ai-art/accept.py <name> [<name> ...] [--from <path-to-webp-dir>]
"""
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
args = sys.argv[1:]
src_dir = os.path.join(HERE, "pending")
if "--from" in args:
    i = args.index("--from")
    src_dir = args[i + 1]
    args = args[:i] + args[i + 2:]


def trim_bars(im: Image.Image) -> Image.Image:
    """Drops near-black rows at the top and bottom (letterbox bars)."""
    g = im.convert("L")
    w, h = g.size
    def dark(y):
        row = g.crop((0, y, w, y + 1)).resize((64, 1))
        return max(row.tobytes()) < 18
    top = 0
    while top < h // 5 and dark(top):
        top += 1
    bottom = h
    while bottom > h - h // 5 and dark(bottom - 1):
        bottom -= 1
    return im.crop((0, top, w, bottom)) if (top or bottom < h) else im


def to_16x9(im: Image.Image) -> Image.Image:
    w, h = im.size
    if w / h > 16 / 9:
        nw = int(h * 16 / 9)
        return im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    nh = int(w * 9 / 16)
    return im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))


cfg_path = os.path.join(HERE, "scenes.json")
cfg = json.load(open(cfg_path))
for name in args:
    if name not in cfg["scenes"]:
        sys.exit(f"unknown scene {name}")
    im = Image.open(os.path.join(src_dir, name + ".webp")).convert("RGB")
    im = to_16x9(trim_bars(im)).resize((960, 540), Image.LANCZOS)
    im.save(os.path.join(ROOT, "public", "scenes", name + ".jpg"), quality=84, optimize=True, progressive=True)
    if name not in cfg["done"]:
        cfg["done"].append(name)
    print("accepted", name)
json.dump(cfg, open(cfg_path, "w"), indent=2)
open(cfg_path, "a").write("\n")

ts = os.path.join(ROOT, "src", "components", "art", "aiStills.ts")
names = ", ".join(f'"{n}"' for n in sorted(cfg["done"]))
open(ts, "w").write(f'''// Generated by scripts/ai-art/accept.py. Scenes with new AI place art: the still is shown
// instead of the old stock video. See public/scenes/CREDITS.md.
export const AI_STILLS = new Set<string>([{names}]);
''')
print("aiStills.ts:", len(cfg["done"]), "scenes")
